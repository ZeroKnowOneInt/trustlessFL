PREFIX = "Aion/input_validation/"
ARCHIVE_SHA256 = "dff11dfbdf8c40121c01220b3292007cfea5b8401ecd413af0b7701ebbc742f3"
INIT_SHA256 = "7f54772524fa46fb0568c604f44a6235dfabbdecbe298b78e8e18119ade27d3e"
INITIALIZATION = (1, 8, 173569775688864, 5000999999999999)


def digest(content):
    return hashlib.sha256(content).hexdigest()


def write_json(path, data):
    with path.open("x") as stream:
        json.dump(data, stream, indent=2, allow_nan=False)
        stream.write("\n")


def replace_exact(text, old, new, count=1):
    if text.count(old) != count:
        raise ValueError(f"patch anchor count changed: {old!r}")
    return text.replace(old, new)


def unified_patch(original, adapted, name):
    lines = difflib.unified_diff(original.decode().splitlines(True),
                                adapted.decode().splitlines(True),
                                fromfile="original/" + name, tofile="runtime/" + name)
    # difflib omits the marker for source files without a final newline.
    return "".join(line if line.endswith("\n") else line + "\n\\ No newline at end of file\n"
                   for line in lines)


def adapt_source(name, content):
    """Mechanical, guarded changes only in the generated execution copy."""
    text = content.decode("utf-8")
    if name == "FL_Backdoor_CV/roles/server.py":
        text = replace_exact(text, "self.model = torch.load(", "self.model = safe_checkpoint_load(")
        text = "from _aion_safe_runtime import safe_checkpoint_load\n" + text
    elif name == "FL_Backdoor_CV/roles/aggregation_rules.py":
        text = replace_exact(text, ".cuda()", ".to(args.device)", count=2)
        anchor = "    # computation for next round\n"
        trace = (
            "    # Read-only instrumentation; no random draws or model changes.\n"
            "    global last_trace\n"
            "    last_trace = dict(selected_positions=indices_selected.cpu().tolist(),\n"
            "                      masked_l2=l2_norm.cpu().tolist(),\n"
            "                      bound=float(b), max_mask=float(max_mask),\n"
            "                      mask_sum_linf=linf_norm_shprg)\n\n"
        )
        text = replace_exact(text, anchor, trace + anchor)
    elif name == "FL_Backdoor_CV/shprg/shprg.py":
        # The only input pickle becomes a literal whose pinned bytes were checked.
        # matrix_840 is generated by this run in its new private working directory.
        text = replace_exact(text, "return pickle.load(file)", f"return {INITIALIZATION!r}")
    return text.encode("utf-8")


def prepare_runtime(archive, inspection, work):
    from experiments.audit_artifact import hashes
    from experiments.probe_aion_checkpoint import CHECKPOINT, checkpoint_arrays

    if hashes(archive)["sha256"] != ARCHIVE_SHA256:
        raise ValueError("unreviewed artifact archive")
    inventory = json.loads((inspection / "inventory.json").read_text())
    runtime = work / "input_validation"
    runtime.mkdir()
    changes, source_hashes, diff = [], {}, []
    with zipfile.ZipFile(archive) as bundle:
        arrays = checkpoint_arrays(bundle.read(CHECKPOINT))
        init = bundle.read(PREFIX + "FL_Backdoor_CV/shprg/initialization_values")
        if digest(init) != INIT_SHA256:
            raise ValueError("SHPRG initialization changed")
        for entry in inventory["files"]:
            name = entry["path"]
            if not name.startswith(PREFIX) or not entry.get("text_extracted"):
                continue
            relative = Path(name.removeprefix(PREFIX))
            if relative.is_absolute() or ".." in relative.parts:
                raise ValueError("unsafe artifact path")
            if relative.suffix not in {".py", ".yaml"}:
                continue
            source = inspection / "source" / name
            original = source.read_bytes()
            if digest(original) != entry["sha256"] or original != bundle.read(name):
                raise ValueError(f"reviewed source changed: {name}")
            adapted = adapt_source(str(relative), original)
            target = runtime / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open("xb") as stream:
                stream.write(adapted)
            source_hashes[str(relative)] = {"original": digest(original), "runtime": digest(adapted)}
            if adapted != original:
                changes.append(str(relative))
                diff.append(unified_patch(original, adapted, str(relative)))
        target = runtime / "FL_Backdoor_CV/shprg/initialization_values"
        with target.open("xb") as stream:
            stream.write(init)
    with (work / "runtime.patch").open("x") as stream:
        stream.writelines(diff)
    write_json(work / "source-hashes.json", source_hashes)
    return runtime, arrays, changes


def tensor_digest(values):
    checksum = hashlib.sha256()
    for name, tensor in values.items():
        array = tensor.detach().cpu().contiguous().numpy()
        checksum.update(name.encode())
        checksum.update(str(array.shape).encode())
        checksum.update(str(array.dtype).encode())
        checksum.update(array.tobytes())
    return checksum.hexdigest()


def summarize_rounds(rounds):
    if not rounds:
        raise ValueError("no completed rounds")
    peak = max(row["poison_accuracy"] for row in rounds)
    return {"round_count": len(rounds),
            "ASR_mean_trainer": sum(row["poison_accuracy"] for row in rounds) / len(rounds),
            "TER_mean_trainer": 1 - sum(row["accuracy"] for row in rounds) / len(rounds),
            "ASR_max_check_results": peak,
            "TER_at_max_ASR_check_results": min(1 - row["accuracy"] for row in rounds
                                                 if row["poison_accuracy"] == peak)}


def execute(options, runtime, arrays, report):
    import numpy as np
    import torch

    torch.set_num_threads(1)
    torch.set_num_interop_threads(1)
    bridge = types.ModuleType("_aion_safe_runtime")

    def safe_checkpoint_load(path, map_location):
        if not str(path).endswith("/fmnist/avg_300.pth") or str(map_location) != "cpu":
            raise ValueError("only the reviewed CPU checkpoint is supported")
        from FL_Backdoor_CV.models.create_model import create_model
        # Deserialization did not initialize parameters in the original code.
        # Preserve its RNG semantics when constructing our safe replacement.
        with torch.random.fork_rng(devices=[]):
            model = create_model()
        model.load_state_dict({key: torch.from_numpy(value.copy()) for key, value in arrays.items()}, strict=True)
        return model

    bridge.safe_checkpoint_load = safe_checkpoint_load
    sys.modules[bridge.__name__] = bridge
    sys.path.insert(0, str(runtime))
    sys.argv = ["trainer.py", "--dataset=fmnist", "--params=utils/fmnist_params.yaml",
                "--resume=1", "--resumed_name=fmnist/avg_300.pth", "--rounds=1000",
                "--participant_population=500", "--participant_sample_size=100",
                "--class_imbalance=0", "--balance=0.99", "--classes_per_client=2",
                "--is_poison=1", "--random_compromise=0", "--poison_prob=0.5",
                "--number_of_adversaries=20", "--mal_boost=400", "--device=cpu",
                "--weight=0.1", "--min_threshold=0.1", f"--retrain_rounds={options.rounds}",
                f"--aggregation_rule={options.rule}"]
    report["artifact_argv"] = sys.argv[:]
    os.chdir(runtime)
    from FL_Backdoor_CV.roles import server as server_module
    from FL_Backdoor_CV.roles import aggregation_rules
    from FL_Backdoor_CV.roles.trainer import Trainer
    from configs import args

    initial = {}
    for method, loss_key, accuracy_key in [("validate", "loss", "accuracy"),
                                           ("validate_poison", "poison_loss", "poison_accuracy")]:
        original = getattr(server_module.Server, method)

        def observed(self, _original=original, _loss=loss_key, _accuracy=accuracy_key):
            result = _original(self)
            if self.current_round == 300:
                initial.update({_loss: result[0], _accuracy: result[1]})
            return result

        setattr(server_module.Server, method, observed)

    trainer = Trainer()
    server = trainer.server
    helper = server.helper
    partitions = [list(map(int, loader.sampler.indices)) for loader in helper.train_data]
    flat = [i for partition in partitions for i in partition]
    poison_indices = list(map(int, helper.poison_images_ind))
    partition_report = {"client_indices": partitions, "poison_test_indices": poison_indices,
                        "assigned_examples": len(flat), "unique_assigned_examples": len(set(flat)),
                        "unassigned_examples": len(helper.train_dataset) - len(set(flat)),
                        "poison_sample_count": len(poison_indices),
                        "poison_unique_count": len(set(poison_indices)),
                        "poison_train_test_overlap": True}
    write_json(options.output / "partition.json", partition_report)
    report.update({"initial_checkpoint": initial, "args": vars(args).copy(),
                   "helper_params": helper.params, "poison_rounds": sorted(server.poison_rounds),
                   "parameter_count": sum(p.numel() for p in server.model.parameters()),
                   "initial_model_sha256": tensor_digest(server.model.state_dict()),
                   "partition_sha256": digest((options.output / "partition.json").read_bytes()),
                   "partition_summary": {k: v for k, v in partition_report.items()
                                         if k not in {"client_indices", "poison_test_indices"}}})
    write_json(options.output / "preflight.json", report)
    print("PREFLIGHT " + json.dumps(initial), flush=True)
    aggregation_trace = {}
    original_rule = getattr(server_module, options.rule)

    def observed_aggregation(updates, *rest):
        aggregation_trace.clear()
        aggregation_trace["updates_sha256"] = tensor_digest(updates)
        if not all(torch.isfinite(value).all().item() for value in updates.values()):
            raise ValueError("non-finite local updates")
        result = original_rule(updates, *rest)
        if options.rule == "aion":
            aggregation_trace.update(aggregation_rules.last_trace)
        else:
            aggregation_trace["selected_positions"] = list(range(args.participant_sample_size))
        return result

    setattr(server_module, options.rule, observed_aggregation)
    rows = []
    # Same select -> train/aggregate -> clean evaluation -> poison evaluation
    # sequence as Trainer.train. Save JSON every round instead of every 20.
    with (options.output / "rounds.jsonl").open("x", buffering=1) as stream:
        for _ in range(options.rounds):
            started = time.monotonic()
            server.select_participants()
            server.train_and_aggregate(global_lr=args.global_lr)
            loss, accuracy = server.validate()
            poison_loss, poison_accuracy = server.validate_poison()
            selected = [server.participants[i] for i in aggregation_trace["selected_positions"]]
            row = {"round": server.current_round, "attack_round": server.current_round in server.poison_rounds,
                   "participants": server.participants, "selected_clients": selected,
                   "selected_count": len(selected),
                   "selected_malicious": len(set(selected) & set(server.adversary_list)),
                   "selected_benign": len(set(selected) - set(server.adversary_list)),
                   "loss": loss, "accuracy": accuracy, "poison_loss": poison_loss,
                   "poison_accuracy": poison_accuracy, "TER": 1 - accuracy,
                   "seconds": time.monotonic() - started, "aggregation": aggregation_trace.copy(),
                   "model_sha256": tensor_digest(server.model.state_dict())}
            stream.write(json.dumps(row, allow_nan=False) + "\n")
            stream.flush()
            rows.append(row)
            print("ROUND " + json.dumps({k: row[k] for k in ["round", "attack_round", "accuracy",
                   "poison_accuracy", "selected_count", "selected_malicious", "seconds"]}), flush=True)
    matrix = runtime / "matrix_840"
    report.update({"status": "completed", "metrics": summarize_rounds(rows), "rounds": rows,
                   "matrix_840_sha256": digest(matrix.read_bytes()) if matrix.exists() else None})
    # Plain arrays, not executable model pickle. These are continuation weights,
    # not a full RNG/optimizer-state resume checkpoint.
    np.savez(options.output / "final-weights.npz", **{key: value.detach().cpu().numpy()
                                                      for key, value in server.model.state_dict().items()})
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", type=Path, default=Path(".cache/aion-artifact/Aion.zip"))
    parser.add_argument("--inspection", type=Path, default=Path(".cache/aion-artifact/inspection-15870338"))
    parser.add_argument("--data", type=Path, default=Path(".cache/fashion-mnist"))
    parser.add_argument("--rule", choices=["avg", "aion"], required=True)
    parser.add_argument("--rounds", type=int, default=2)
    parser.add_argument("--output", type=Path, required=True, help="new directory; refuses overwrite")
    options = parser.parse_args()
    if not 1 <= options.rounds <= 60:
        parser.error("rounds must be 1..60")
    for key in ["archive", "inspection", "data", "output"]:
        setattr(options, key, getattr(options, key).resolve())
    data = prepare(options.data, download=False)
    options.output.mkdir(parents=True, exist_ok=False)
    adapter = Path(__file__).read_bytes()
    with (options.output / "adapter-used.py").open("xb") as stream:
        stream.write(adapter)
    os.environ.setdefault("MPLBACKEND", "Agg")
    os.environ["MPLCONFIGDIR"] = str(options.output / "matplotlib-cache")
    started = time.monotonic()
    runtime, arrays, changes = prepare_runtime(options.archive, options.inspection, options.output)
    dataset_link = runtime / "FL_Backdoor_CV/data/fmnist"
    dataset_link.parent.mkdir(parents=True, exist_ok=True)
    dataset_link.symlink_to(options.data, target_is_directory=True)
    report = {"status": "started", "started_utc": datetime.now(timezone.utc).isoformat(),
              "scope": "official centralized input-validation CPU pilot" if options.rounds < 60
                       else "official centralized input-validation CPU 60-round run",
              "paper_reproduction_complete": False, "secure_aggregation_executed": False,
              "flower_executed": False, "rule": options.rule, "requested_rounds": options.rounds,
              "dataset": data, "archive_sha256": ARCHIVE_SHA256,
              "adapter_sha256": digest(adapter), "changed_source_files": changes,
              "python": sys.version, "platform": platform.platform(),
              "device": "cpu", "torch_threads": 1, "matrix_policy": "fresh per run; original RNG",
              "packages": {dist.metadata["Name"]: dist.version for dist in importlib.metadata.distributions()},
              "deviations": ["CPU instead of original CUDA; two device calls adapted",
                             "restricted checkpoint decoder and RNG-preserving model construction",
                             "pinned SHPRG initialization tuple instead of input pickle execution",
                             "original Trainer initialization and Server loop; JSON telemetry each round",
                             "no periodic pickle model saves; final arrays saved as NPZ"],
              "limitations": ["original poison train/test indices overlap; ASR is not held-out",
                              "MGF sees plaintext centrally; no privacy/secure aggregation claim",
                              "CPU runtime is not comparable to paper GPU timings",
                              "natural artifact RNG schedule; later avg/aion participant draws may diverge"]}
    with (options.output / "stdout.log").open("x", buffering=1) as log:
        try:
            with contextlib.redirect_stdout(log), contextlib.redirect_stderr(log):
                report = execute(options, runtime, arrays, report)
        except Exception:
            import traceback
            report["status"] = "failed"
            report["traceback"] = traceback.format_exc()
            write_json(options.output / "failure.json", report)
            raise
    report["elapsed_seconds"] = time.monotonic() - started
    report["peak_rss_kib_linux"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    write_json(options.output / "result.json", report)
    print(json.dumps({"output": str(options.output), "status": report["status"],
                      "initial": report["initial_checkpoint"], "metrics": report["metrics"]}, indent=2))


if __name__ == "__main__":
    main()
